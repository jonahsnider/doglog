//! Agent control on desktop. Each window serves agent commands on a local socket, see `window.rs`, and the `doglog`
//! command relays to them as an MCP server, see `mcp.rs`, or as terminal commands, see `cli.rs`.
//!
//! Windows speak newline-delimited JSON-RPC 2.0 with two methods: `info` returns the window's details for
//! `window_list`, and `call` runs a command given `{ name, args }`.

mod bridge;
pub mod cli;
pub mod mcp;
mod socket;
pub mod window;

use serde::{Deserialize, Serialize};
use serde_json::{Map, Value};
use std::sync::LazyLock;

/// The agent commands Studio offers on desktop, generated from `src/agent`
#[derive(Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Api {
    /// Changes only when commands change incompatibly
    pub api_version: u64,
    /// The MCP server's instructions, also the description in `doglog --help`
    pub instructions: String,
    pub commands: Vec<Command>,
}

#[derive(Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Command {
    pub name: String,
    pub description: String,
    /// JSON Schema of the command's input object
    pub input_schema: Map<String, Value>,
    /// Answered by the `doglog` command itself instead of a window, ex. `window_list`
    pub bridge: bool,
    /// Captures images, so it's only offered where Studio supports capture
    pub capture: bool,
}

pub static API: LazyLock<Api> = LazyLock::new(|| {
    let mut api: Api = serde_json::from_str(include_str!("../../agent-api.json")).expect("agent-api.json is invalid");
    api.commands
        .retain(|command| cfg!(any(target_os = "macos", windows)) || !command.capture);
    api
});

/// A command that runs in a window, rather than in the `doglog` command
fn window_command(name: &str) -> Option<&'static Command> {
    API.commands
        .iter()
        .find(|command| command.name == name && !command.bridge)
}

#[derive(Serialize, Deserialize, Debug)]
pub struct RpcError {
    pub code: i64,
    pub message: String,
}

impl RpcError {
    /// A command that failed, rather than one that doesn't exist or got invalid input
    fn failed(message: impl ToString) -> Self {
        Self {
            code: -32000,
            message: message.to_string(),
        }
    }
}

#[derive(Serialize, Deserialize)]
struct Request {
    jsonrpc: String,
    id: Value,
    method: String,
    #[serde(default)]
    params: Value,
}

impl Request {
    fn new(method: &str, params: Value) -> Self {
        Self {
            jsonrpc: "2.0".to_owned(),
            id: 1.into(),
            method: method.to_owned(),
            params,
        }
    }
}

#[derive(Serialize, Deserialize)]
struct Response {
    jsonrpc: String,
    id: Value,
    // `null` is a valid result, which deserializes as `None`
    #[serde(skip_serializing_if = "Option::is_none")]
    result: Option<Value>,
    #[serde(skip_serializing_if = "Option::is_none")]
    error: Option<RpcError>,
}

impl Response {
    fn new(id: Value, result: Result<Value, RpcError>) -> Self {
        let (result, error) = match result {
            Ok(result) => (Some(result), None),
            Err(error) => (None, Some(error)),
        };
        Self {
            jsonrpc: "2.0".to_owned(),
            id,
            result,
            error,
        }
    }

    fn into_result(self) -> Result<Value, RpcError> {
        match self.error {
            Some(error) => Err(error),
            None => Ok(self.result.unwrap_or(Value::Null)),
        }
    }
}

/// `value` as one line of the protocol
fn to_line(value: &impl Serialize) -> String {
    let mut line = serde_json::to_string(value).expect("JSON-RPC messages serialize");
    line.push('\n');
    line
}

/// Run `future` to completion, for terminal commands that run before Tauri starts its own runtime
fn block_on<F: Future>(future: F) -> F::Output {
    tokio::runtime::Builder::new_multi_thread()
        .enable_all()
        .build()
        .expect("failed to start the async runtime")
        .block_on(future)
}

